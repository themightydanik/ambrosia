export const billingCopy = (lang) => copy[lang] || copy.en;
export function periodLabel(period, lang) {
  const match = /^P(\d+)([DWMY])$/.exec(period);
  if (!match) return period;
  const words = {
    en: { D: "day", W: "week", M: "month", Y: "year" },
    uk: { D: "дн.", W: "тиж.", M: "міс.", Y: "р." },
    ru: { D: "дн.", W: "нед.", M: "мес.", Y: "г." },
  };
  return `${match[1]} ${(words[lang] || words.en)[match[2]]}`;
}
